// bundled editor/i18n.js): English source strings ARE the keys, so a missing
// entry falls back to English and nothing ever renders blank. carino-lang.js
// (deferred, loaded just before this script) resolves the locale and fires
// 'carino:langchange'; this file owns the dictionaries and re-applies.
//
// Markup:  data-i18n            → textContent
//          data-i18n-html       → innerHTML (leaves carrying <em>/<code>)
//          data-i18n-title      → title attribute
//          data-i18n-placeholder→ placeholder attribute
//          data-i18n-aria-label → aria-label attribute
// Dynamic: app.js wraps its literals in T() / TF() / TN() → window.t / .tn.
//          Template rows are cloned outside the document, so app.js calls
//          window.applyI18nIn(clone) on each one.
//
// Deliberately NOT translated, because they are protocol identifiers a
// technologist matches character-for-character against the modality's config:
