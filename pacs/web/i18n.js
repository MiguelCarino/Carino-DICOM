// C-ECHO, ORM^O01, PDF, port numbers, AE titles. Log lines and API messages
// come from the Python engine and stay in the server's language.
// Such a string may carry NO entry in the blocks below — the English literal
// is the identifier, so the t() fallback renders it verbatim in every locale
// ('Print SCP', 'MWL SCP', 'mTLS' and '→ SC' were deliberately emptied out).
// An identity entry (value byte-identical to the key) is equivalent and also
// appears; both mean "leave it alone". Do not "fix" either by translating.
//
// Two documented exceptions, both deliberate:
//   ru writes RIS as 'РИС' throughout — it is a real Russian abbreviation and
//     is used consistently across every RIS string, not drift.
//   ru renders the 'Worklist' card/chip label as 'MWL' because the Russian
//     noun ('Рабочий список') busts the navbar chip budget; ja keeps
//     'ワークリスト', which fits. Width decides, per locale.

