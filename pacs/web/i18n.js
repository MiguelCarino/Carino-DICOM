// Which form index a count selects, per language.
const RULE = {
    ja: function () { return 0; },                       // no grammatical plural
    ru: function (n) {
        if (n % 10 === 1 && n % 100 !== 11) return 0;     // 1, 21, 31…
        if (n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14)) return 1;  // 2-4, 22-24…
        return 2;                                          // 0, 5-20, 25-30…
    },
};
function ruleFor(lang) { return RULE[lang] || function (n) { return n === 1 ? 0 : 1; }; }

// ── Runtime ─────────────────────────────────────────────────────────────

function currentFleetLang() { return (window.CarinoLang && window.CarinoLang.current) || 'en'; }

function t(key) {
    const dict = I18N[currentFleetLang()];
    return (dict && dict[key]) || key;
}
window.t = t;   // app.js and carino-navbar.js wrap literals with (window.t||String)(…)

function tn(n, key) {
    const lang = currentFleetLang();
    const forms = (PLURALS[lang] && PLURALS[lang][key]) || (PLURALS.en && PLURALS.en[key]);
    let s = key;
    if (forms && forms.length) {
        const i = ruleFor(forms === PLURALS.en[key] ? 'en' : lang)(Math.abs(Number(n) || 0));
        s = forms[Math.min(i, forms.length - 1)];
    }
    return s.replace(/\{n\}/g, n);
}
window.tn = tn;

// Static markup, scoped to `root` so <template> clones can be translated too
// (template content lives in a DocumentFragment that document-wide queries
// never reach). The original English is captured in a data-* attribute on the
// first pass, so switching locales back and forth stays lossless.
function applyI18nIn(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.textContent.trim();
        el.textContent = t(el.dataset.i18nKey);
    });
    scope.querySelectorAll('[data-i18n-html]').forEach((el) => {
        if (!el.dataset.i18nKeyHtml) el.dataset.i18nKeyHtml = el.innerHTML.trim().replace(/\s+/g, ' ');
        el.innerHTML = t(el.dataset.i18nKeyHtml);
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
        if (!el.dataset.i18nTitle) el.dataset.i18nTitle = el.title;
        el.title = t(el.dataset.i18nTitle);
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        if (!el.dataset.i18nPlaceholder) el.dataset.i18nPlaceholder = el.placeholder;
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    scope.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
        if (!el.dataset.i18nAriaLabel) el.dataset.i18nAriaLabel = el.getAttribute('aria-label') || '';
        el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
    });
    return scope;
}
window.applyI18nIn = applyI18nIn;

function applyI18n() {
    document.documentElement.lang = currentFleetLang();
    applyI18nIn(document);
}

// carino-lang.js is deferred and precedes this script, so CarinoLang exists by
// DOMContentLoaded. app.js registers its own langchange handler to redraw the
// parts of the dashboard it rendered itself.
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyI18n);
} else {
    applyI18n();
}
window.addEventListener('carino:langchange', applyI18n);
