// JS-owned status elements: retranslate only while they still show the
// initial string (in any language) — never clobber a runtime value.
function retranslateIfUntouched(id, key) {
    const el = document.getElementById(id);
    if (!el) return;
    const cur = el.textContent.trim();
    const known = cur === key || Object.values(I18N).some((d) => d[key] === cur);
    if (known) el.textContent = t(key);
}

function applyI18n() {
    document.documentElement.lang = currentFleetLang();
    applyStaticI18n();
    applyAttrI18n();
    retranslateIfUntouched('fileNamePill', 'No file loaded');
    retranslateIfUntouched('cmpStatusPill', 'Load two files to compare');
    retranslateIfUntouched('loadText', 'Loading…');
}

// carino-lang.js is also deferred and precedes this script, so CarinoLang
// exists by DOMContentLoaded; re-apply whenever the user switches language.
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyI18n);
} else {
    applyI18n();
}
window.addEventListener('carino:langchange', applyI18n);
